DOWNLOAD_LIMIT = 48 * 1024 * 1024


def download(name, url, expected, target):
    def expired(_signum, _frame):
        raise TimeoutError('Download timed out: ' + name)

    print('Downloading ' + name + ' on the VPS...', flush=True)
    request = urllib.request.Request(url, headers={'User-Agent': 'MeshVPS console installer'})
    previous = signal.signal(signal.SIGALRM, expired)
    signal.alarm(180)
    try:
        with urllib.request.urlopen(request, timeout=20) as source, target.open('wb') as output:
            size = 0
            digest = hashlib.sha256()
            while chunk := source.read(128 * 1024):
                size += len(chunk)
                if size > DOWNLOAD_LIMIT:
                    raise RuntimeError('Download exceeded its size limit: ' + name)
                digest.update(chunk)
                output.write(chunk)
            if digest.hexdigest() != expected:
                raise RuntimeError('Downloaded file did not match its SHA-256: ' + name)
    finally:
        signal.alarm(0)
        signal.signal(signal.SIGALRM, previous)


def main():
    if os.geteuid() != 0:
        raise RuntimeError('Run this command as root (sudo -i).')
    if platform.machine() != 'x86_64' or not Path('/run/systemd/system').is_dir():
        raise RuntimeError('Use a Debian/Ubuntu x86_64 VPS with systemd.')

    with tempfile.TemporaryDirectory(prefix='meshvps-console-') as directory:
        stage = Path(directory)
        for name, (url, expected) in ARTIFACTS.items():
            download(name, url, expected, stage / name)

        token = uuid.uuid4()
        request = {
            'client_id': token.hex,
            'client_uuid': str(token),
            'hashes': {name: digest for name, (_, digest) in ARTIFACTS.items()},
        }
        if enrollment := os.environ.get('MESHVPS_ENROLL_TOKEN'):
            request['enrollment_token'] = str(uuid.UUID(enrollment))
        pc_source = base64.b64decode(PC_GRE)
        (stage / 'pc-gre.py').write_bytes(pc_source)
        request['hashes']['pc-gre.py'] = hashlib.sha256(pc_source).hexdigest()
        (stage / 'request.json').write_text(json.dumps(request), encoding='utf-8')
        installer = {'__name__': 'meshvps_deploy'}
        installer_source = base64.b64decode(INSTALLER)
        exec(compile(installer_source, 'deploy.py', 'exec'), installer)
        print('Starting MeshVPS services...', flush=True)
        result = installer['install'](stage, installer_source)
        parameters = {}
        if result.get('bootstrap_udp_port'):
            parameters.update(awg=result['bootstrap_udp_port'], key=result['bootstrap_server_key'])
        if gateway := result.get('pc_gre'):
            parameters.update(pcgre=gateway['address'], pcpin=gateway['public_key_sha256'])
        elif error := result.get('pc_gre_error'):
            print(f'GRE from PC unavailable. Yggdrasil is ready: {error}', flush=True)
        if error := result.get('enrollment_error'):
            print(f'SSH enrollment through GRE unavailable: {error}', flush=True)
        elif result.get('pc_gre'):
            print('SSH enrollment through GRE is ready. Return to MeshVPS and register using your SSH login.', flush=True)
        query = '?' + urllib.parse.urlencode(parameters) if parameters else ''
        print('\nCopy this private code into MeshVPS (Import code):\n')
        print(f"meshvps://{token}@[{result['address']}]:{result['port']}{query}", flush=True)


if __name__ == '__main__':
    main()
