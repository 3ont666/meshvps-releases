    if (SERVER_ROOT / 'proxy.json').exists() and os.environ.get('MESHVPS_FORCE_UPDATE') != '1':
        print('MeshVPS is already installed. Existing services were left unchanged.', flush=True)
        print('Return to MeshVPS, choose "MeshVPS already installed" and register using SSH through GRE.', flush=True)
        print('If a server update is required, ask the owner to schedule a one-time maintenance update.', flush=True)
        return

    with tempfile.TemporaryDirectory(prefix='meshvps-console-') as directory:
